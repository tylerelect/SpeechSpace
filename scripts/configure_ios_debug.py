#!/usr/bin/env python3
"""Write private Xcode Debug Dart defines; no third-party dependencies."""

import argparse
import base64
import os
from pathlib import Path
import tempfile
from urllib.parse import urlsplit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--url', help='HTTPS API origin, without /api/snapshot')
    mode.add_argument('--demo', action='store_true', help='Override stale generated defines with demo mode')
    args = parser.parse_args()
    url = (args.url or '').rstrip('/')
    token = '' if args.demo else os.environ.get('APP_DEV_TOKEN', '')
    if not args.demo:
        parsed = urlsplit(url)
        if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
            parser.error('--url must be an HTTPS API URL without credentials, query, or fragment')
        if not token.strip():
            parser.error('Export APP_DEV_TOKEN from your local .env first; no token was written')
    defines = ','.join(base64.b64encode(value.encode()).decode() for value in (
        f'API_BASE_URL={url}', f'DEV_API_TOKEN={token}',
    ))
    target = Path(__file__).resolve().parents[1] / 'ios/Flutter/Debug.local.xcconfig'
    # Atomic replacement with owner-only permissions, including when updating.
    fd, temporary = tempfile.mkstemp(dir=target.parent, prefix='.debug-config-')
    try:
        with os.fdopen(fd, 'w') as output:
            output.write('// Local development only. Generated by scripts/configure_ios_debug.py.\n')
            output.write('// Overrides Generated.xcconfig for Debug only. Base64 is not encryption.\n')
            output.write(f'DART_DEFINES = {defines}\n')
        os.replace(temporary, target)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    print(f'Configured Xcode Debug: {"demo mode" if args.demo else url}; token not printed.')


if __name__ == '__main__':
    main()
