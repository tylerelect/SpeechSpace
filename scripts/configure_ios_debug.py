#!/usr/bin/env python3
"""Write private Xcode Debug Dart defines; no third-party dependencies."""

import argparse
import base64
import json
import os
from pathlib import Path
import tempfile
import shlex
from urllib.parse import urlsplit


def read_token(path):
    """Read one dotenv value without executing shell code or expanding secrets."""
    if not path.exists():
        return os.environ.get('APP_DEV_TOKEN', '')
    token = ''
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith('export '):
            line = line[7:].lstrip()
        key, separator, value = line.partition('=')
        if separator and key.strip() == 'APP_DEV_TOKEN':
            values = shlex.split(value, comments=True)
            if len(values) != 1:
                raise ValueError('APP_DEV_TOKEN must contain one nonempty value')
            token = values[0]
    return token


def write_private(target, content):
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(dir=target.parent, prefix='.debug-config-')
    try:
        with os.fdopen(fd, 'w') as output:
            output.write(content)
        os.replace(temporary, target)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--url', default='https://api.speechspace.health', help='HTTPS API origin')
    parser.add_argument('--env-file', type=Path, default=root / '.env', help='Backend dotenv file (default: repository .env)')
    parser.add_argument('--sync-android', action='store_true', help='Also update config/dev.local.json for Android Studio')
    args = parser.parse_args()
    url = args.url.rstrip('/')
    try:
        token = read_token(args.env_file)
    except ValueError:
        parser.error('Cannot parse APP_DEV_TOKEN in the env file; no files were written')
    parsed = urlsplit(url)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
        parser.error('--url must be an HTTPS API URL without credentials, query, or fragment')
    if not token.strip():
        parser.error('Set APP_DEV_TOKEN in the env file first; no token was written')
    defines = ','.join(base64.b64encode(value.encode()).decode() for value in (
        f'API_BASE_URL={url}', f'DEV_API_TOKEN={token}',
    ))
    target = root / 'ios/Flutter/Debug.local.xcconfig'
    android = root / 'config/dev.local.json'
    settings = {}
    if args.sync_android and android.exists():
        settings = json.loads(android.read_text())
        if not isinstance(settings, dict):
            parser.error('config/dev.local.json must contain a JSON object')
    # Atomic replacement with owner-only permissions, including when updating.
    write_private(target, '// Local development only. Generated by scripts/configure_ios_debug.py.\n'
                  '// Overrides Generated.xcconfig for Debug only. Base64 is not encryption.\n'
                  f'DART_DEFINES = {defines}\n')
    if args.sync_android:
        settings.update(API_BASE_URL=url, DEV_API_TOKEN=token)
        write_private(android, json.dumps(settings, indent=2) + '\n')
        print('Android Studio local defines synchronized; token not printed.')
    print(f'Configured Xcode Debug: {url}; token not printed.')


if __name__ == '__main__':
    main()
